"""Install and remove the automatic OpenCode adapter.

The adapter is one generated JavaScript plugin. It runs the installed Python
core as a short-lived subprocess for each oversized tool result, so there is no
daemon, no port, and no token to manage. The file is generated with the
interpreter and the dedicated store home baked in; a version change or a new
interpreter rewrites it with a backup, and a foreign file is never overwritten.

The plugin lives beside OpenCode's config (``<config>/plugins/sutra.js``), so
it applies to every project that uses that config. OpenCode loads plugin files
from the config tree; the config file itself is only needed for the optional
MCP recovery entry.
"""

from __future__ import annotations

import importlib.resources
import json
import os
import pathlib
import sys
import tempfile

from . import installer

PLUGIN_NAME = "sutra.js"
MARKER = "// Generated by sutra install for OpenCode. Reinstall to update."


def default_home() -> pathlib.Path:
    """Dedicated store for OpenCode; never the user's Hermes profile."""
    override = os.environ.get("SUTRA_OPENCODE_HOME")
    if override:
        return pathlib.Path(override).expanduser()
    return pathlib.Path.home() / ".sutra"


def plugin_path(config_path: str | pathlib.Path | None = None) -> pathlib.Path:
    return installer.opencode_config(
        str(config_path) if config_path is not None else None
    ).parent / "plugins" / PLUGIN_NAME


def render(python: str | None = None, home: str | pathlib.Path | None = None) -> str:
    """The plugin text with the interpreter and store home embedded as JSON."""
    package = __package__ or "sutra"
    template = importlib.resources.files(package).joinpath("opencode_plugin.js").read_text(
        encoding="utf-8")
    home_path = pathlib.Path(home) if home is not None else default_home()
    return (template
            .replace("__SUTRA_PYTHON__", json.dumps(python or sys.executable))
            .replace("__SUTRA_HOME__", json.dumps(str(home_path))))


def configured(config_path: str | pathlib.Path | None = None) -> bool:
    try:
        text = plugin_path(config_path).read_text(encoding="utf-8")
    except OSError:
        return False
    return MARKER in text


def _new_file(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd, temporary = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".",
                                     suffix=".tmp")
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def install(*, dry_run: bool = False, python: str | None = None,
            home: str | pathlib.Path | None = None,
            config_path: str | pathlib.Path | None = None) -> int:
    """Write the generated plugin; return a process exit code."""
    path = plugin_path(config_path)
    text = render(python=python, home=home)
    if path.exists():
        current = path.read_text(encoding="utf-8")
        if current == text:
            print(f"sutra: {path} already has the current OpenCode plugin; nothing to do")
            return 0
        if MARKER not in current:
            print(f"sutra: {path} exists and was not generated by SUTRA; refusing to "
                  f"overwrite it", file=sys.stderr)
            return 1
    if dry_run:
        print(f"sutra: dry run, would write the OpenCode plugin to {path} (no file was written)")
        return 0
    if path.exists():
        backup = installer._write(path, text)  # timestamped backup beside the file
        print(f"sutra: updated the OpenCode plugin at {path}")
        print(f"sutra: backup at {backup}")
    else:
        _new_file(path, text)
        print(f"sutra: installed the OpenCode plugin at {path}")
    print("sutra: restart OpenCode so it loads the plugin")
    return 0


def uninstall(*, dry_run: bool = False,
              config_path: str | pathlib.Path | None = None) -> int:
    """Remove the generated plugin; refuse to touch a foreign file."""
    path = plugin_path(config_path)
    if not path.exists():
        print(f"sutra: {path} does not exist; nothing to uninstall")
        return 0
    text = path.read_text(encoding="utf-8")
    if MARKER not in text:
        print(f"sutra: {path} was not generated by SUTRA; leaving it in place",
              file=sys.stderr)
        return 1
    if dry_run:
        print(f"sutra: dry run, would remove the OpenCode plugin at {path} "
              f"(no file was written)")
        return 0
    path.unlink()
    print(f"sutra: removed the OpenCode plugin at {path}")
    return 0


def status() -> dict:
    path = plugin_path()
    return {
        "plugin": str(path),
        "automatic": configured(),
        "home": str(default_home()),
    }
