"""CI must stay read-only and exercise the installed CLI, not just the source."""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
WORKFLOWS = ROOT / ".github" / "workflows"
WORKFLOW = WORKFLOWS / "ci.yml"


def test_ci_uses_a_read_only_token_by_default():
    text = WORKFLOW.read_text(encoding="utf-8")
    assert re.search(r"(?m)^permissions:\n  contents: read$", text), (
        "CI must declare contents: read so pull requests cannot inherit a "
        "write-capable default token")
    assert "contents: write" not in text
    assert "write-all" not in text


def test_the_package_job_exercises_the_installed_cli():
    text = WORKFLOW.read_text(encoding="utf-8")
    assert "Exercise the installed CLI across the supported adapters" in text
    for command in (
        "sutra detect",
        "sutra doctor --json",
        "sutra status --json",
        "sutra install --client \"$client\" --dry-run",
        "sutra uninstall --client \"$client\" --dry-run",
        "sutra install --client opencode",
        "sutra uninstall --client opencode",
        "sutra install --client openclaw",
        "sutra uninstall --client openclaw",
        "sutra detect --client openclaw --json",
    ):
        assert command in text, command
    assert 'openclaw_plugin="$CLI_HOME/.openclaw/plugins/sutra.js"' in text
    assert 'grep -q "Generated by sutra install for OpenClaw"' in text
    assert "before=$(find \"$CLI_HOME\"" in text
    assert "after=$(find \"$CLI_HOME\"" in text
    assert 'test "$before" = "$after"' in text


def test_every_action_is_pinned_to_a_commit_with_a_version_comment():
    for path in sorted(WORKFLOWS.glob("*.yml")):
        for line in path.read_text(encoding="utf-8").splitlines():
            if " uses: " not in line or line.lstrip().startswith("#"):
                continue
            reference = line.split("@", 1)[1].split("#", 1)[0].strip()
            assert re.fullmatch(r"[0-9a-f]{40}", reference), f"{path.name}: {line}"
            assert " # " in line, f"{path.name}: {line}"


def test_every_workflow_declares_top_level_permissions():
    # A workflow without a `permissions:` block inherits whatever the repository
    # default is; every file here must state its own floor.
    for path in sorted(WORKFLOWS.glob("*.yml")):
        text = path.read_text(encoding="utf-8")
        assert re.search(r"(?m)^permissions:\n", text), (
            f"{path.name} must declare top-level permissions")
        assert "write-all" not in text, f"{path.name} must not grant write-all"


def test_no_workflow_uses_pull_request_target():
    # pull_request_target runs with a write token and the base repository's
    # secrets, so a checkout of the pull request head there is unsafe.
    for path in sorted(WORKFLOWS.glob("*.yml")):
        text = path.read_text(encoding="utf-8")
        assert "pull_request_target" not in text, (
            f"{path.name} must not run untrusted pull request code with a "
            "privileged token")


def test_the_test_jobs_install_the_telemetry_extra():
    text = WORKFLOW.read_text(encoding="utf-8")
    assert text.count('pip install -e ".[telemetry]"') >= 4, (
        "every normal product-suite job must install the optional OTel stack "
        "so the telemetry failure tests exercise real exporters")
