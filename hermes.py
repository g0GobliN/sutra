"""Install and verify SUTRA's native Hermes Agent plugin.

Hermes discovers native plugins as a directory with ``plugin.yaml`` and
``register(ctx)``, then loads only the names in ``plugins.enabled``. The
documented enable/validate commands are used instead of editing config.yaml:
the host owns its config and capability consent. The plugin directory is
copied from this installed package, so a pip-installed SUTRA has everything
Hermes needs without a checkout.

This module never writes a user's Hermes config. ``hermes plugins enable`` and
``hermes plugins disable`` are the only config-changing operations, and a
failed install restores the previous directory.
"""

from __future__ import annotations

import os
import pathlib
import re
import shutil
import subprocess
import sys
import time

PLUGIN_NAME = "sutra"
MARKER = ".sutra-generated"
MANIFEST = "plugin.yaml"


def binary() -> str | None:
    return shutil.which("hermes")


def home() -> pathlib.Path:
    override = os.environ.get("HERMES_HOME")
    if override:
        return pathlib.Path(override).expanduser()
    return pathlib.Path.home() / ".hermes"


def config_path() -> pathlib.Path:
    return home() / "config.yaml"


def plugin_dir() -> pathlib.Path:
    return home() / "plugins" / PLUGIN_NAME


def source_dir() -> pathlib.Path:
    return pathlib.Path(__file__).resolve().parent


def _run(args: list[str], timeout: int = 90):
    executable = binary()
    if executable is None:
        return None
    try:
        return subprocess.run(
            [executable, *args], capture_output=True, text=True,
            timeout=timeout, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError):
        return None


def _manifest_name(path: pathlib.Path) -> str | None:
    try:
        text = (path / MANIFEST).read_text(encoding="utf-8")
    except OSError:
        return None
    match = re.search(r"^name:\s*[\"']?([^\"'\s#]+)", text, re.MULTILINE)
    return match.group(1) if match else None


def is_ours(path: pathlib.Path | None = None) -> bool:
    target = path or plugin_dir()
    if target.is_symlink():
        return False
    if not target.is_dir() or _manifest_name(target) != PLUGIN_NAME:
        return False
    if (target / MARKER).is_file():
        return True
    try:
        init = (target / "__init__.py").read_text(encoding="utf-8")
    except OSError:
        return False
    return "def register(ctx)" in init and "SUTRA" in init


def _copy_plugin(destination: pathlib.Path) -> None:
    source = source_dir()
    destination.mkdir(parents=True, mode=0o700)
    for item in source.iterdir():
        if not item.is_file() or item.suffix != ".py" and item.name != MANIFEST:
            continue
        shutil.copy2(item, destination / item.name)
    (destination / MARKER).write_text(
        "Generated by sutra install for Hermes Agent. Reinstall to update.\n",
        encoding="utf-8")


def _backup(path: pathlib.Path) -> pathlib.Path:
    stamp = time.strftime("%Y%m%dT%H%M%S")
    backup = path.with_name(f"{path.name}.bak-{stamp}")
    suffix = 1
    while backup.exists():
        suffix += 1
        backup = path.with_name(f"{path.name}.bak-{stamp}-{suffix}")
    path.rename(backup)
    return backup


def _restore(path: pathlib.Path, backup: pathlib.Path | None) -> None:
    if path.exists():
        shutil.rmtree(path)
    if backup is not None and backup.exists():
        backup.rename(path)


def _enabled() -> bool | None:
    if binary() is None or not plugin_dir().is_dir():
        return None
    result = _run(["plugins", "show", PLUGIN_NAME], timeout=30)
    if result is None or result.returncode != 0:
        return None
    text = f"{result.stdout}\n{result.stderr}"
    match = re.search(r"Status:\s*(enabled|disabled)", text, re.IGNORECASE)
    if match:
        return match.group(1).lower() == "enabled"
    if re.search(r"\benabled\b", text, re.IGNORECASE):
        return True
    return None


def status() -> dict:
    path = plugin_dir()
    return {
        "client": "hermes",
        "binary": binary(),
        "home": str(home()),
        "config": str(config_path()),
        "plugin": str(path),
        "installed": is_ours(path),
        "enabled": _enabled(),
        "automatic": bool(is_ours(path) and _enabled()),
        "tier": "automatic",
    }


def install(*, dry_run: bool = False) -> int:
    """Copy the plugin, validate it with Hermes, then enable it."""
    if binary() is None:
        print("sutra: hermes is not installed; nothing to configure", file=sys.stderr)
        return 1
    target = plugin_dir()
    if target.is_symlink():
        print(f"sutra: refusing to replace the symlink at {target}", file=sys.stderr)
        return 1
    if target.exists() and not is_ours(target):
        print(f"sutra: {target} is not a SUTRA plugin; refusing to overwrite it",
              file=sys.stderr)
        return 1
    if target.resolve() == source_dir().resolve():
        print(f"sutra: {target} is the source checkout; it is already the plugin")
        return 0
    if dry_run:
        print(f"sutra: dry run, would install the Hermes plugin at {target} "
              f"and run: hermes plugins enable {PLUGIN_NAME}")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    temporary = target.parent / f".{PLUGIN_NAME}.tmp-{time.time_ns()}"
    backup = None
    try:
        _copy_plugin(temporary)
        if target.exists():
            backup = _backup(target)
        temporary.rename(target)
    except OSError as exc:
        if temporary.exists():
            shutil.rmtree(temporary, ignore_errors=True)
        _restore(target, backup)
        print(f"sutra: could not install the Hermes plugin: {exc}", file=sys.stderr)
        return 1
    validation = _run(["plugins", "validate", str(target)], timeout=120)
    if validation is None or validation.returncode != 0:
        detail = ((validation.stderr or validation.stdout) if validation else "hermes did not run")
        _restore(target, backup)
        print(f"sutra: Hermes rejected the plugin: {(detail or '').strip()[-300:]}",
              file=sys.stderr)
        return 1
    enabled = _run(["plugins", "enable", PLUGIN_NAME], timeout=60)
    if enabled is None or enabled.returncode != 0:
        detail = ((enabled.stderr or enabled.stdout) if enabled else "hermes did not run")
        _restore(target, backup)
        print(f"sutra: could not enable the Hermes plugin: "
              f"{(detail or '').strip()[-300:]}", file=sys.stderr)
        return 1
    if _enabled() is not True:
        _restore(target, backup)
        print("sutra: Hermes did not report the plugin as enabled after install",
              file=sys.stderr)
        return 1
    print(f"sutra: installed and enabled the Hermes plugin at {target}")
    print("sutra: restart Hermes' gateway so middleware loading is refreshed")
    return 0


def uninstall(*, dry_run: bool = False) -> int:
    target = plugin_dir()
    if not target.exists():
        print(f"sutra: {target} does not exist; nothing to uninstall")
        return 0
    if not is_ours(target):
        print(f"sutra: {target} was not generated by SUTRA; leaving it in place",
              file=sys.stderr)
        return 1
    if dry_run:
        print(f"sutra: dry run, would disable the Hermes plugin and remove {target}")
        return 0
    disabled = _run(["plugins", "disable", PLUGIN_NAME], timeout=45)
    if disabled is None or disabled.returncode != 0:
        print("sutra: Hermes did not confirm the disable; removing the plugin "
              "directory anyway", file=sys.stderr)
    shutil.rmtree(target)
    print(f"sutra: removed the Hermes plugin at {target}")
    return 0


def doctor() -> dict:
    report = {
        "client": "hermes",
        "binary": binary(),
        "home": str(home()),
        "plugin": str(plugin_dir()),
        "installed": False,
        "enabled": None,
        "automatic": False,
        "tier": "automatic",
        "ok": False,
        "status": "fail",
        "probe": "hermes is not installed",
    }
    target = plugin_dir()
    if report["binary"] is None:
        if target.exists():
            report.update({"installed": is_ours(target), "status": "fail",
                           "probe": "the SUTRA plugin directory exists, but the hermes "
                                    "executable is missing; the plugin cannot be validated"})
        else:
            report["status"] = "not-installed"
        return report
    if not is_ours(target):
        report["probe"] = "the SUTRA Hermes plugin is not installed"
        return report
    report["installed"] = True
    validation = _run(["plugins", "validate", str(target)], timeout=120)
    if validation is None or validation.returncode != 0:
        detail = ((validation.stderr or validation.stdout) if validation else "hermes did not run")
        report["probe"] = f"Hermes validation failed: {(detail or '').strip()[-300:]}"
        return report
    enabled = _enabled()
    report["enabled"] = enabled
    if enabled is not True:
        report["probe"] = "the plugin is installed but not enabled in Hermes"
        return report
    report.update({
        "automatic": True,
        "ok": True,
        "status": "pass",
        "probe": "Hermes validation passed and the plugin is enabled",
    })
    return report


def format_doctor(report: dict) -> str:
    if "error" in report:
        return f"hermes: error: {report['error']}"
    return (f"hermes: plugin={'pass' if report.get('installed') else 'fail'} "
            f"enabled={'yes' if report.get('enabled') is True else 'no'} "
            f"automatic={'yes' if report.get('ok') else 'no'} "
            f"status={report.get('status')} probe={report.get('probe')}")
