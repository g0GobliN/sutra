"""Install and verify SUTRA's native Hermes Agent plugin.

Hermes discovers native plugins as a directory with ``plugin.yaml`` and
``register(ctx)``, then loads only the names in ``plugins.enabled``. The
documented enable/validate commands are used instead of editing config.yaml:
the host owns its config and capability consent. The plugin directory is
copied from this installed package, so a pip-installed SUTRA has everything
Hermes needs without a checkout.

This module never writes a user's Hermes config. ``hermes plugins enable`` and
``hermes plugins disable`` are the only config-changing operations, and a
failed install restores the previous directory.
"""

from __future__ import annotations

import hashlib
import os
import pathlib
import re
import shutil
import subprocess
import time

from .ui import print_error, print_info, print_success

PLUGIN_NAME = "sutra"
MARKER = ".sutra-generated"
MANIFEST = "plugin.yaml"
# Hermes prepares its isolated runtime on the first validation and can exceed
# five minutes on a cold isolated home; allow that preparation to finish.
VALIDATION_TIMEOUT = 600


def binary() -> str | None:
    return shutil.which("hermes")


def home() -> pathlib.Path:
    override = os.environ.get("HERMES_HOME")
    if override:
        return pathlib.Path(override).expanduser()
    return pathlib.Path.home() / ".hermes"


def config_path() -> pathlib.Path:
    return home() / "config.yaml"


def plugin_dir() -> pathlib.Path:
    return home() / "plugins" / PLUGIN_NAME


def source_dir() -> pathlib.Path:
    return pathlib.Path(__file__).resolve().parent


def _run(args: list[str], timeout: int = 90):
    executable = binary()
    if executable is None:
        return None
    try:
        return subprocess.run(
            [executable, *args], capture_output=True, text=True,
            timeout=timeout, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError):
        return None


def _why(result, timeout: int) -> str:
    """Explain a failed host call: its own output, or why there is none."""
    if result is None:
        return (f"no result from hermes within {timeout}s "
                "(missing binary, spawn failure or timeout)")
    text = (result.stderr or result.stdout or "").strip()
    if text:
        return text[-300:]
    return f"hermes exited {result.returncode} without a message"


def _manifest_name(path: pathlib.Path) -> str | None:
    try:
        text = (path / MANIFEST).read_text(encoding="utf-8")
    except OSError:
        return None
    match = re.search(r"^name:\s*[\"']?([^\"'\s#]+)", text, re.MULTILINE)
    return match.group(1) if match else None


def is_ours(path: pathlib.Path | None = None) -> bool:
    target = path or plugin_dir()
    if target.is_symlink():
        return False
    if not target.is_dir() or _manifest_name(target) != PLUGIN_NAME:
        return False
    if (target / MARKER).is_file():
        return True
    try:
        init = (target / "__init__.py").read_text(encoding="utf-8")
    except OSError:
        return False
    return "def register(ctx)" in init and "SUTRA" in init


def _copy_plugin(destination: pathlib.Path) -> None:
    source = source_dir()
    destination.mkdir(parents=True, mode=0o700)
    for item in source.iterdir():
        if not item.is_file() or item.suffix != ".py" and item.name != MANIFEST:
            continue
        shutil.copy2(item, destination / item.name)
    (destination / MARKER).write_text(
        "Generated by sutra install for Hermes Agent. Reinstall to update.\n",
        encoding="utf-8")


def _backup(path: pathlib.Path) -> pathlib.Path:
    """Move the current plugin aside, outside the directory Hermes scans for plugins.

    A backup beside the plugin (``sutra.bak-<stamp>`` inside ``<home>/plugins``) is itself a
    plugin directory with the same manifest name, so the next load can pick the stale copy
    and run the previous code. Keep the copy in ``<home>/plugin-backups`` instead, which the
    loader never scans.
    """
    stamp = time.strftime("%Y%m%dT%H%M%S")
    root = path.parent.parent / "plugin-backups"
    try:
        root.mkdir(parents=True, exist_ok=True, mode=0o700)
    except OSError:
        root = path.parent
    backup = root / f"{path.name}-{stamp}"
    suffix = 1
    while backup.exists():
        suffix += 1
        backup = root / f"{path.name}-{stamp}-{suffix}"
    try:
        path.rename(backup)
    except OSError:
        shutil.move(str(path), str(backup))
    return backup


def _restore(path: pathlib.Path, backup: pathlib.Path | None) -> None:
    if path.exists():
        shutil.rmtree(path)
    if backup is not None and backup.exists():
        backup.rename(path)


def _enabled() -> bool | None:
    if binary() is None or not plugin_dir().is_dir():
        return None
    result = _run(["plugins", "show", PLUGIN_NAME], timeout=30)
    if result is None or result.returncode != 0:
        return None
    text = f"{result.stdout}\n{result.stderr}"
    match = re.search(r"Status:\s*(enabled|disabled)", text, re.IGNORECASE)
    if match:
        return match.group(1).lower() == "enabled"
    if re.search(r"\benabled\b", text, re.IGNORECASE):
        return True
    return None


def status() -> dict:
    path = plugin_dir()
    report = deployment(path, source_dir())
    return {
        "client": "hermes",
        "binary": binary(),
        "home": str(home()),
        "config": str(config_path()),
        "plugin": str(path),
        "installed": is_ours(path),
        "enabled": _enabled(),
        "current": report["current"],
        "missing_stages": report["missing"],
        "automatic": bool(is_ours(path) and _enabled() and report["current"] is not False),
        "tier": "automatic",
    }


_DECLARED_KEYS = ("provides_middleware", "provides_hooks", "provides_tools")
# The manifest is compared by its declared stages, not by bytes: two copies
# that declare the same stages may still format the file differently.
_COMPARED_FILES = ("prompt.py", "__init__.py", "store.py", "metrics.py")


def _declared(path: pathlib.Path) -> dict[str, list[str]]:
    """Return the stages a plugin.yaml in ``path`` declares.

    The manifest is a short flat YAML file, so this reads it line by line
    instead of adding a YAML dependency to a plugin that must install without
    one. A missing or unreadable manifest yields an empty declaration, which the
    caller reports as unknown rather than as current.
    """
    try:
        text = (path / MANIFEST).read_text(encoding="utf-8")
    except OSError:
        return {}
    declared: dict[str, list[str]] = {}
    current: str | None = None
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if not line[:1].isspace():
            key, _, value = stripped.partition(":")
            current = key if key in _DECLARED_KEYS and not value.strip() else None
            if current:
                declared[current] = []
            continue
        if current and stripped.startswith("-"):
            item = stripped[1:].strip().strip("\"'")
            if item:
                declared[current].append(item)
    return declared


def _digest(path: pathlib.Path) -> str | None:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def deployment(installed: pathlib.Path | None = None,
               source: pathlib.Path | None = None) -> dict:
    """Compare the installed plugin copy with the package it came from.

    A copy can be enabled, valid and still predate the code the user installed:
    Hermes loads whatever the directory declares, so a copy that never declared
    ``llm_request`` keeps running only the stages it has. This reports that
    difference instead of letting ``sutra doctor`` call such a copy healthy.
    """
    target = installed or plugin_dir()
    origin = source or source_dir()
    report: dict = {
        "installed": str(target), "source": str(origin),
        "current": None, "missing": {}, "extra": {}, "changed_files": [],
        "reason": "",
    }
    theirs = _declared(target)
    ours = _declared(origin)
    if not ours:
        report["reason"] = "this package declares no plugin stages to compare against"
        return report
    if not theirs:
        report["reason"] = f"{target} has no readable {MANIFEST}"
        return report

    missing = {
        key: [stage for stage in ours.get(key, []) if stage not in theirs.get(key, [])]
        for key in _DECLARED_KEYS
    }
    extra = {
        key: [stage for stage in theirs.get(key, []) if stage not in ours.get(key, [])]
        for key in _DECLARED_KEYS
    }
    report["missing"] = {key: value for key, value in missing.items() if value}
    report["extra"] = {key: value for key, value in extra.items() if value}
    changed = []
    for name in _COMPARED_FILES:
        mine, theirs_digest = _digest(origin / name), _digest(target / name)
        if mine is None:
            continue
        if theirs_digest is None:
            changed.append({"file": name, "state": "missing"})
        elif mine != theirs_digest:
            changed.append({"file": name, "state": "differs"})
    report["changed_files"] = changed

    if report["missing"]:
        report["current"] = False
        absent = ", ".join(stage for stages in report["missing"].values() for stage in stages)
        report["reason"] = (
            f"the installed copy predates this package: it does not declare {absent}")
    elif changed:
        report["current"] = False
        report["reason"] = ("the installed copy declares the same stages but its files differ "
                            "from this package")
    else:
        report["current"] = True
        report["reason"] = "the installed copy matches this package"
    return report


def install(*, dry_run: bool = False) -> int:
    """Copy the plugin, validate it with Hermes, then enable it."""
    if binary() is None:
        print_error("sutra: hermes is not installed; nothing to configure")
        return 1
    target = plugin_dir()
    if target.is_symlink():
        print_error(f"refusing to replace the symlink at {target}")
        return 1
    if target.exists() and not is_ours(target):
        print_error(f"{target} is not a SUTRA plugin; refusing to overwrite it")
        return 1
    if target.resolve() == source_dir().resolve():
        print_info(f"{target} is the source checkout; it is already the plugin")
        return 0
    if dry_run:
        print_info(f"sutra: dry run, would install the Hermes plugin at {target} and run: hermes plugins enable {PLUGIN_NAME}")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    temporary = target.parent / f".{PLUGIN_NAME}.tmp-{time.time_ns()}"
    backup = None
    try:
        _copy_plugin(temporary)
        if target.exists():
            backup = _backup(target)
        temporary.rename(target)
    except OSError as exc:
        if temporary.exists():
            shutil.rmtree(temporary, ignore_errors=True)
        _restore(target, backup)
        print_error(f"could not install the Hermes plugin: {exc}")
        return 1
    validation = _run(["plugins", "validate", str(target)], timeout=VALIDATION_TIMEOUT)
    if validation is None or validation.returncode != 0:
        _restore(target, backup)
        print_error("Hermes rejected the plugin: "
                    + _why(validation, VALIDATION_TIMEOUT))
        return 1
    enabled = _run(["plugins", "enable", PLUGIN_NAME], timeout=60)
    if enabled is None or enabled.returncode != 0:
        _restore(target, backup)
        print_error("could not enable the Hermes plugin: " + _why(enabled, 60))
        return 1
    if _enabled() is not True:
        _restore(target, backup)
        print_error("Hermes did not report the plugin as enabled after install")
        return 1
    print_success(f"sutra: installed and enabled the Hermes plugin at {target}")
    print_info("sutra: restart Hermes' gateway so middleware loading is refreshed")
    return 0


def uninstall(*, dry_run: bool = False) -> int:
    target = plugin_dir()
    if not target.exists():
        print_info(f"sutra: {target} does not exist; nothing to uninstall")
        return 0
    if not is_ours(target):
        print_error(f"{target} was not generated by SUTRA; leaving it in place")
        return 1
    if dry_run:
        print_info(f"sutra: dry run, would disable the Hermes plugin and remove {target}")
        return 0
    disabled = _run(["plugins", "disable", PLUGIN_NAME], timeout=45)
    if disabled is None or disabled.returncode != 0:
        print_error("Hermes did not confirm the disable; removing the plugin directory anyway")
    shutil.rmtree(target)
    print_success(f"sutra: removed the Hermes plugin at {target}")
    return 0


def doctor() -> dict:
    report = {
        "client": "hermes",
        "binary": binary(),
        "home": str(home()),
        "plugin": str(plugin_dir()),
        "installed": False,
        "enabled": None,
        "automatic": False,
        "tier": "automatic",
        "ok": False,
        "status": "fail",
        "probe": "hermes is not installed",
    }
    target = plugin_dir()
    if report["binary"] is None:
        if target.exists():
            report.update({"installed": is_ours(target), "status": "fail",
                           "probe": "the SUTRA plugin directory exists, but the hermes "
                                    "executable is missing; the plugin cannot be validated"})
        else:
            report["status"] = "not-installed"
        return report
    if not is_ours(target):
        report["probe"] = "the SUTRA Hermes plugin is not installed"
        return report
    report["installed"] = True
    validation = _run(["plugins", "validate", str(target)], timeout=VALIDATION_TIMEOUT)
    if validation is None or validation.returncode != 0:
        report["probe"] = ("Hermes validation failed: "
                           + _why(validation, VALIDATION_TIMEOUT))
        return report
    enabled = _enabled()
    report["enabled"] = enabled
    if enabled is not True:
        report["probe"] = "the plugin is installed but not enabled in Hermes"
        return report
    copy_report = deployment(target, source_dir())
    report["copy"] = copy_report
    if copy_report["current"] is False:
        report.update({
            "automatic": True,
            "ok": False,
            "status": "stale",
            "probe": (copy_report["reason"]
                      + "; run `sutra install --client hermes` and restart the gateway"),
        })
        return report
    report.update({
        "automatic": True,
        "ok": True,
        "status": "pass",
        "probe": "Hermes validation passed, the plugin is enabled and the copy matches this package",
    })
    return report


def format_doctor(report: dict) -> str:
    if "error" in report:
        return f"hermes: error: {report['error']}"
    copy = report.get("copy") or {}
    current = copy.get("current")
    copy_text = "unknown" if current is None else ("current" if current else "stale")
    line = (f"hermes: plugin={'pass' if report.get('installed') else 'fail'} "
            f"enabled={'yes' if report.get('enabled') is True else 'no'} "
            f"copy={copy_text} "
            f"automatic={'yes' if report.get('ok') else 'no'} "
            f"status={report.get('status')} probe={report.get('probe')}")
    missing = copy.get("missing") or {}
    if missing:
        stages = ", ".join(stage for stages in missing.values() for stage in stages)
        line += f" missing_stages={stages}"
    return line
