"""Prepare an isolated Hermes home that loads SUTRA from this checkout.

Nothing here touches ``~/.hermes``. The target directory gets its own
``config.yaml`` (one custom provider pointing at the mock server) and a
``plugins/sutra`` copy of the Python modules in this repository, which is
exactly how Hermes discovers a native directory plugin. A marker file makes a
non-empty destination refusable, so a wrong path cannot clobber a real home.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

MARKER = ".sutra-ab-home"
PLUGIN_MARKER = ".sutra-generated"
MANIFEST = "plugin.yaml"

CONFIG = """\
_config_version: 53
model:
  default: mock-model
  provider: custom
  base_url: {base_url}
  api_key_env: SUTRA_AB_KEY
  max_in_progress: 1
plugins:
  enabled:
    - sutra
"""


def copy_plugin(source: Path, plugin_dir: Path) -> list[str]:
    """Copy the plugin modules the way ``sutra install`` does, and report them."""
    plugin_dir.mkdir(parents=True, exist_ok=True)
    copied: list[str] = []
    for item in sorted(source.iterdir()):
        if item.is_file() and (item.suffix == ".py" or item.name == MANIFEST):
            shutil.copy2(item, plugin_dir / item.name)
            copied.append(item.name)
    (plugin_dir / PLUGIN_MARKER).write_text(
        "Generated by the SUTRA agent harness. Regenerate to update.\n", encoding="utf-8")
    return copied


def prepare(home: Path, source: Path, base_url: str, force: bool = False) -> dict[str, object]:
    """Create or refresh an isolated home; returns what was written."""
    home = home.expanduser()
    if home.exists() and any(home.iterdir()):
        if not force and not (home / MARKER).exists():
            raise SystemExit(f"refusing to overwrite non-harness directory: {home}")
        if not force:
            raise SystemExit(f"{home} already prepared; pass --force to refresh the plugin copy")
    if not (source / "plugin.yaml").is_file():
        raise SystemExit(f"source does not look like the SUTRA package: {source}")
    home.mkdir(parents=True, exist_ok=True)
    (home / MARKER).write_text("SUTRA agent A/B harness home.\n", encoding="utf-8")
    (home / "config.yaml").write_text(CONFIG.format(base_url=base_url.rstrip("/")), encoding="utf-8")
    copied = copy_plugin(source, home / "plugins" / "sutra")
    return {
        "home": str(home),
        "plugin": str(home / "plugins" / "sutra"),
        "files": copied,
        "config": str(home / "config.yaml"),
    }


def main(argv: list[str] | None = None) -> int:
    default_source = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--home", type=Path, required=True)
    parser.add_argument("--source", type=Path, default=default_source)
    parser.add_argument("--base-url", default="http://127.0.0.1:8787/v1")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args(argv)
    result = prepare(args.home, args.source, args.base_url, args.force)
    print(f"home:    {result['home']}")
    print(f"plugin:  {result['plugin']} ({len(result['files'])} files)")
    print(f"config:  {result['config']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
